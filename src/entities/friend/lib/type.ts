/**
 * Пропсы для компонента карточки друга.
 * 
 * @description
 * Отображает информацию о пользователе, с которым установлена дружба,
 * и предоставляет интерфейс для отправки сообщения.
 */
export type FriendCardProps = {
  /** Уникальный идентификатор пользователя-друга */
  id: number;
  
  /** Имя пользователя для отображения */
  username: string;
  
  /** Ссылка на аватар или `null`, если аватар не задан */
  avatarUrl: string | null;
  
  /** Дата начала дружбы в формате для отображения */
  friendsSince: string;
  
  /** Обработчик клика по действию «Написать сообщение». Передаёт ID пользователя */
  onMessageClick?: (userId: number) => void;
};